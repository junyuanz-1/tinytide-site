#!/usr/bin/env python3
"""Builds the site from src/: the three pages from src/tpl, and assets/i18n.js
from src/i18n/<language>.json. English (en.json) is written into the HTML;
the other languages are swapped in by assets/site.js.

    python3 src/build.py

Edit the templates and translation files, never the generated HTML or
assets/i18n.js. Every language file must have every key in en.json.
"""
import json
import pathlib
import re
import sys

SRC = pathlib.Path(__file__).resolve().parent
SITE = SRC.parent
LANGUAGES = ["zh-Hans", "zh-Hant", "ja", "ko", "es", "pt-BR", "fr", "de"]

en = json.loads((SRC / "i18n/en.json").read_text())
header = (SRC / "tpl/_header.html").read_text()
pages = {
    "index.html": ("", '<a class="hide-sm" href="support/" data-i18n="nav.support">{{nav.support}}</a>\n        <a class="hide-sm" href="privacy/" data-i18n="nav.privacy">{{nav.privacy}}</a>'),
    "privacy/index.html": ("../", '<a class="hide-sm" href="../support/" data-i18n="nav.support">{{nav.support}}</a>'),
    "support/index.html": ("../", '<a class="hide-sm" href="../privacy/" data-i18n="nav.privacy">{{nav.privacy}}</a>'),
}


def fill(text):
    return re.sub(r"\{\{([\w.]+)\}\}", lambda m: en[m.group(1)], text)


for rel, (root, links) in pages.items():
    html = (SRC / "tpl" / rel).read_text()
    html = html.replace("{{HEADER}}", header.replace("{{NAVLINKS}}", links).replace("{{ROOT}}", root or "./"))
    out = SITE / rel
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(fill(html))

translations = {}
for lang in LANGUAGES:
    strings = json.loads((SRC / "i18n" / f"{lang}.json").read_text())
    missing = sorted(set(en) - set(strings))
    if missing:
        sys.exit(f"{lang}.json is missing {missing[:5]}")
    translations[lang] = strings
(SITE / "assets/i18n.js").write_text(
    "// Generated by src/build.py from src/i18n. Do not edit by hand.\nwindow.TINYTIDE_I18N = "
    + json.dumps(translations, ensure_ascii=False, indent=1) + ";\n"
)
print("built pages; languages:", ", ".join(["en"] + LANGUAGES))
